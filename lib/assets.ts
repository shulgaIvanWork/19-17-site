import { assetVersions } from '@/content/assetVersions';

/** Начало версионированного адреса. Тот же префикс разбирает rewrite в
 *  next.config.ts: сегмент версии там снимается, и файл читается из public
 *  по своему настоящему пути. */
const versionPrefix = '/v';

/** Адрес файла из public с версией его содержимого в пути.
 *
 *  Браузер и оптимизатор картинок помнят ответ по адресу, а не по файлу.
 *  Новый снимок, положенный под прежним именем, до них не доходит, пока не
 *  истечет срок хранения: у оптимизатора это minimumCacheTTL, тридцать суток.
 *  Так и вышло 2026-09-23 с фотографиями команды - на диске лежали новые,
 *  сервер отдавал прежние, и жесткая перезагрузка не помогала.
 *
 *  Версия в пути меняет адрес вместе с содержимым: вернувшийся посетитель
 *  запрашивает адрес, которого у него в кеше нет, и получает новый снимок в
 *  тот же заход. Неизменные файлы сохраняют прежний адрес и остаются в кеше.
 *
 *  Файла нет в таблице - адрес возвращается как есть: таблицу собирает
 *  scripts/assetVersions.mjs перед dev и сборкой. */
export function versioned(src: string): string {
  const version = assetVersions[src];
  return version ? `${versionPrefix}/${version}${src}` : src;
}
