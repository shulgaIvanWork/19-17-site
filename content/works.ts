import type { ImageSlot } from './products';

export type Work = {
  id: string;
  /** Файл макета, из которого собрана карточка. Держим связь в коде: без нее
   *  непонятно, какой снимок класть в слот и что уточнять у заказчика. */
  source: string;
  /** Тип работы на плашке карточки. */
  kind: string;
  title: string;
  body: string;
  /** Короткие подписи под описанием: что входило в работу. */
  parts: string[];
  /** Первый экран макета: то, что видно в карточке. */
  image: ImageSlot;
  /** Макет целиком, открывается по нажатию на карточку. Размеры нужны, чтобы
   *  страница не прыгала: снимок лендинга высокий, пропорции у всех разные. */
  full?: { src: string; width: number; height: number };
};

export type FlowStep = {
  /** Номер этапа. Пишется страницей, а не берется с листа: внутри листов
   *  нумерация сбита - лист с референсами подписан вторым этапом, хотя идет
   *  третьим. Верхние подписи с листов сняты при сборке. */
  n: number;
  title: string;
  /** Что на этом этапе делается. */
  body: string;
  /** Лист с результатом этапа. Слот не ImageSlot: у того пропорции ограничены
   *  3/2 и 4/5, а у листов они свои - от 5:1 у задачи до 1:2 у готовой
   *  страницы. Размеры держат место до загрузки, чтобы страница не прыгала. */
  shot: { src: string; width: number; height: number; alt: string };
};

